/** Translate generated explanations while leaving creator names and source titles intact. */
export function localizeSearchReason(reason: string, locale: 'en' | 'zh-CN'): string {
  if (locale === 'en') return reason;
  if (REASON_ZH[reason]) return REASON_ZH[reason];
  const creator = /^From (.+)$/u.exec(reason);
  if (creator) return `来自 ${creator[1]}`;
  const months = /^Recommended in (\d+) distinct months on HN$/u.exec(reason);
  if (months) return `在 ${months[1]} 个不同月份中获得 HN 推荐`;
  const similar = /^Similar to “(.+)”(?: · (\d+) shared HN recommenders?)?$/u.exec(reason);
  if (similar) return `与《${similar[1]}》相关${similar[2] ? ` · ${similar[2]} 位 HN 用户共同推荐` : ''}`;
  return reason;
}
