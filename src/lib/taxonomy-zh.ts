const aliasPattern = new RegExp(Object.keys(CHINESE_ALIASES).sort((a, b) => b.length - a.length).join('|'), 'gu');

function translateTerms(query: string): string {
  return query
    .replace(/^(?:(?:请帮我找|帮我找|给我推荐|推荐一些|推荐|有没有|关于|有关|如何|怎么|怎样|学习|学会|了解|理解)(?:一下|一些)?\s*)+/u, '')
    .replace(/(?:相关的|的)?(?:入门)?(?:视频|教程|课程)(?:吗|呢)?[？?！!。]*$/u, '')
    .replace(/(?:吗|呢)[？?！!。]*$/u, '')
    .replace(aliasPattern, term => ` ${CHINESE_ALIASES[term]} `)
    // Unknown Chinese is kept, so unsupported terms yield an honest empty
    // result rather than an unrelated broad search or an invented translation.
    .replace(/[，、；。！？：]/gu, ' ')
    .replace(/\s+/g, ' ').trim();
}

/** Normalize known Chinese concepts and goal syntax while preserving Latin tokens. */
export function normalizeChineseQuery(query: string): string {
  if (!/\p{Script=Han}/u.test(query)) return query;
  const clean = query.trim();
  const goal = /(?:我(?:想|希望|打算|要)|想要?|希望|打算|要)(?:去|先|进一步)?(?:学会|学习|学|了解|理解|探索|研究|掌握|入门|搞懂)\s*/u.exec(clean);
  if (goal) {
    const before = clean.slice(0, goal.index).replace(/[，,、；;。\s]+$/u, '');
    const background = /^(?:我)?(?:已经|已)?(?:会|懂|了解|知道|熟悉|掌握|用过|学过)(?:一些|一点|点)?\s*(.+)$/u.exec(before)?.[1];
    const target = translateTerms(clean.slice(goal.index + goal[0].length));
    if (target) return background
      ? `I know ${translateTerms(background)} and want to learn ${target}`
      : `I want to learn ${target}`;
  }
  return translateTerms(clean);
}

